class Intro(Page):
    @staticmethod
    def is_displayed(player: Player):
        return player.round_number == 1

    form_model = 'player'
    form_fields = ['consent']

    @staticmethod
    def error_message(player: Player, values):
        if not values['consent']:
            return "Consent is required to take part."


class Block(Page):
    live_method = live_trial

    @staticmethod
    def js_vars(player: Player):
        return dict(slider_every=C.SLIDER_EVERY,
                    trials_per_block=C.TRIALS_PER_BLOCK,
                    block=player.round_number)


class Results(Page):
    @staticmethod
    def is_displayed(player: Player):
        return player.round_number == C.NUM_ROUNDS

    @staticmethod
    def vars_for_template(player: Player):
        pts = player.participant.vars.get('points', 0)
        rate = player.session.config.get('points_to_currency', 0.02)
        player.payoff = pts * rate
        return dict(points=pts, money=cu(pts * rate))


page_sequence = [Intro, Block, Results]


