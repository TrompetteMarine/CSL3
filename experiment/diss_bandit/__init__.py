"""
diss_bandit — task v3 of the preregistration draft (KGi-DISS-I003/M4), built in I006.

Two-armed bandit, 450 trials in three 150-trial blocks (= the three phases, invisible
to participants), yoked no-deception peer-earnings display with per-block reference
regime (HIGH / LOW), two sliders every 5 trials (fairness; entitlement — the
identification lever), announced non-contingent bonus every 15th trial, restoration
level in block 3 as Factor B (FULL / MODERATE).

Every numeric default traces to the I006 freeze (00_freeze_I006.yaml). Bot data
produced by this app is for pipeline validation only.
"""
import json
import random
import time

from otree.api import *


class C(BaseConstants):
    NAME_IN_URL = 'diss_bandit'
    PLAYERS_PER_GROUP = None
    NUM_ROUNDS = 3                      # 3 blocks = 3 phases
    TRIALS_PER_BLOCK = 150
    SLIDER_EVERY = 5
    BONUS_EVERY = 15                    # announced, non-contingent (windfall probe)
    BONUS_POINTS = 3
    # Phase arm means (good, bad); block 3 from session config (Factor B)
    PHASE_P = {1: (0.65, 0.35), 2: (0.30, 0.15)}
    RESTORATION = {'FULL': (0.65, 0.35),
                   'MODERATE': (0.45, 0.35)}   # I006 design decision: pilot-calibrated
    HIGH_BAND = (0.60, 0.70)            # HIGH-REF yoked stream earnings band
    LOW_BAND_TOL = 0.05                 # LOW-REF: peer matched to own trailing band
    TRAIL_WINDOW = 15                   # trailing window for LOW matching
    POINTS_PER_UNIT = 1


def total_trial(round_number: int, t_in_block: int) -> int:
    return (round_number - 1) * C.TRIALS_PER_BLOCK + t_in_block


class Subsession(BaseSubsession):
    pass


def creating_session(subsession: Subsession):
    cfg = subsession.session.config
    if subsession.round_number != 1:
        return
    rng = random.Random(cfg.get('session_seed', 20261104))
    pool = _load_peer_pool(cfg)
    subsession.session.vars['peer_pool'] = pool
    for p in subsession.get_players():
        prng = random.Random(f"{cfg.get('session_seed', 20261104)}-{p.participant.code}")
        part = p.participant
        # per-participant left/right arm mapping (side counterbalancing)
        part.vars['good_side'] = prng.choice(['left', 'right'])
        # pre-generated outcome sequences per arm, phase-dependent p (reproducible)
        restoration = cfg.get('restoration', 'FULL')
        seqs = {'good': [], 'bad': []}
        for rn in (1, 2, 3):
            pg, pb = C.PHASE_P.get(rn) or C.RESTORATION[restoration]
            for _ in range(C.TRIALS_PER_BLOCK):
                seqs['good'].append(1 if prng.random() < pg else 0)
                seqs['bad'].append(1 if prng.random() < pb else 0)
        part.vars['outcomes'] = seqs
        # block regime sequence: P2 regime = Factor A (session-level);
        # P1/P3 regimes counterbalanced at participant level
        p2 = cfg.get('p2_regime', 'HIGH')
        others = [prng.choice(['HIGH', 'LOW']), prng.choice(['HIGH', 'LOW'])]
        part.vars['regimes'] = {1: others[0], 2: p2, 3: others[1]}
        part.vars['points'] = 0


def _load_peer_pool(cfg):
    """Yoked peer streams. Production: real prior-participant streams (no deception).
    Dev/pilot: placeholder pool generated by tools/make_dev_pool.py and FLAGGED."""
    path = cfg.get('peer_pool_path', '')
    if path:
        with open(path) as f:
            return json.load(f)
    # flagged placeholder: deterministic synthetic pool for development only
    rng = random.Random(99)
    pool = {'placeholder': True, 'streams': []}
    for band_lo in (0.15, 0.30, 0.45, 0.60):
        for k in range(8):
            rate = band_lo + 0.05 + 0.02 * rng.random()
            stream = [1 if rng.random() < rate else 0 for _ in range(450)]
            pool['streams'].append(
                {'id': f'dev-{band_lo:.2f}-{k}', 'rate': sum(stream) / 450.0,
                 'earnings': stream})
    return pool


