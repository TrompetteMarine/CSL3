"""KGi-DISS-I039 parts L and F (estimation): likelihood, scores, information and influence
functions for the lab observables, from the legitimacy distribution generated by ABM
agents performing the task (freeze 00_freeze_I039.yaml). Seeds 136000 (pools), 136010.
    python experiment/analysis/likelihood_I039.py > records/likelihood_I039.txt
Writes records/likelihood_pools_I039.npz and records/likelihood_curves_I039.json.
"""
import json

import numpy as np
from scipy import stats as st

import estimand_core_I038 as ec
import likelihood_core_I039 as lc
import probe_generator as pg

NP = 100000
rng = np.random.default_rng(136000)
print("KGi-DISS-I039 parts L and F (estimation): likelihood from the ABM-generated legitimacy distribution\n")

# ------------------------------------------------------------------ 0. pools
G, raw0 = {}, {}
for p in ec.GATE_POINTS:
    pool = ec.pools('gate', p, NP, rng)
    G[p[0]] = {a: lc.bin_pool(pool[a]) for a in ('HIGH', 'LOW')}
    raw0[p[0]] = {a: (float(pool[a].mean()), float((pool[a] == 0).mean()), float((pool[a] < .05).mean()),
                      float(pool[a].var())) for a in ('HIGH', 'LOW')}
np.savez_compressed('records/likelihood_pools_I039.npz',
                    **{f"{k}_{a}": G[k][a] for k in G for a in ('HIGH', 'LOW')})
print(f"0. legitimacy at probe time, {NP:,} ABM agents per arm and gate point (seed 136000)")
print("   point   HIGH: mean  share at 0  share < .05  variance     LOW: mean  variance")
for k, v in raw0.items():
    print(f"   {k}            {v['HIGH'][0]:.3f}    {v['HIGH'][1]:.3f}       {v['HIGH'][2]:.3f}      {v['HIGH'][3]:.4f}          "
          f"{v['LOW'][0]:.3f}    {v['LOW'][3]:.4f}")

# ------------------------------------------------------------------ 1. gate GK
print("\n1. gate GK: exact kernel k(t | w) against the simulator (1,000,000 simulated participants, seed 136010)")
r2 = np.random.default_rng(136010)
gk_ok = True
for w in (0.0, 0.2, 0.435, 0.85):
    k = lc.kernel_T(np.array([w]), 12.0)[0]
    # the simulator at a fixed weight: event rule, coupling 1, multiplier w / OMEGA, nobody inattentive
    sim = pg.probe_stat(np.full(1000000, w / pg.OMEGA), 1.0, ec.M, ec.SCHEME, 12.0, 'event', r2, inattentive=0.0)
    emp = np.bincount(np.round((sim + 200) / 2.5).astype(int), minlength=161) / len(sim)
    tv = 0.5 * np.abs(emp - k).sum()
    mu = lc.TGRID @ k
    gk_ok &= (tv <= .01) and (abs(mu - sim.mean()) <= .1)
    print(f"   w = {w}: total variation {tv:.4f}; mean exact {mu:.3f}, simulated {sim.mean():.3f}; "
          f"s.d. exact {np.sqrt((lc.TGRID - mu) ** 2 @ k):.3f}, simulated {sim.std():.3f}; sum of probabilities {k.sum():.6f}")
print(f"   GK {'PASS' if gk_ok else 'FAIL'}")

# ------------------------------------------------------------------ models
OTHER = {'P0': 'P4', 'P1': 'P4', 'P2': 'P4', 'P3': 'P4', 'P4': 'P1'}
M = {(k, r): lc.Model(G[k], G[OTHER[k]], r) for k in G for r in ec.RULES}
I38 = json.load(open('records/estimand_map_I038.json'))['psi_model']
print("\n2. model value of psi from the likelihood tables at full coupling (I038 value from its own simulation in brackets)")
for k in G:
    print(f"   {k}: " + "   ".join(f"{r} {M[(k, r)].psi(lc.BASE):.3f} [{I38[f'{k}|{r}']:.3f}]" for r in ec.RULES))

# ------------------------------------------------------------------ 3. information
ZA, ZB = st.norm.ppf(.995), st.norm.ppf(.90)
print("\n3. Fisher information per participant (I_HIGH + I_LOW over one participant in each arm)")
curves = {}
for k in ('P1', 'P4'):
    for r in ec.RULES:
        m = M[(k, r)]
        kap = 'kap' if r == 'event' else 'alpha'
        for c in (1.0, 0.9, 0.75):
            th = {**lc.BASE, 'c': c}
            psi = m.psi(th)
            names_T = ['c', kap, 'sig', 'q']
            names_FT = ['c', kap, 'sig', 'q', 'a', 'sr']
            iT = m.info(th, names_T + ['lam'], False)
            iF = m.info(th, names_FT + ['lam'], True)
            ST, SF = iT['HIGH'] + iT['LOW'], iF['HIGH'] + iF['LOW']
            nT, nF = len(names_T), len(names_FT)
            # oracle (only c unknown); depth unknown; all nuisances unknown
            o_T, o_F = ST[0, 0], SF[0, 0]
            d_T = lc.eff_info(ST[np.ix_([0, nT], [0, nT])])
            d_F = lc.eff_info(SF[np.ix_([0, nF], [0, nF])])
            a_T = lc.eff_info(ST[:nT, :nT])
            a_F = lc.eff_info(SF[:nF, :nF])
            al_T, al_F = lc.eff_info(ST), lc.eff_info(SF)
            # psi: bound against the plug-in (T only, gate point known)
            gpsi = m.grad_psi(th, names_T)
            bound = gpsi @ np.linalg.inv(ST[:nT, :nT]) @ gpsi          # variance x n per arm
            (muH, vH), (muL, vL) = lc.moments(m.pT('HIGH', th)), lc.moments(m.pT('LOW', th))
            vnp = (vH + psi ** 2 * vL) / muL ** 2
            gl = m.grad_psi(th, names_T + ['lam'])
            bound_l = gl @ np.linalg.inv(ST) @ gl
            gF = np.r_[gpsi, 0.0, 0.0]                                 # psi does not depend on a, sr
            bound_F = gF @ np.linalg.inv(SF[:nF, :nF]) @ gF
            se72 = np.sqrt(1 / (72 * al_F))
            ncert = (ZA + ZB) ** 2 / (al_F * 0.1 ** 2)
            print(f"   {k} {r:7s} c = {c}: psi {psi:.3f}")
            print(f"      information for c | only c unknown:        T {o_T:8.3f}   (F, T) {o_F:8.3f}   ratio {o_F / o_T:.2f}")
            print(f"                        | depth unknown as well:  T {d_T:8.3f} ({d_T / o_T:.0%} kept)   (F, T) {d_F:8.3f} ({d_F / o_F:.0%} kept)")
            print(f"                        | all but depth unknown:  T {a_T:8.3f}   (F, T) {a_F:8.3f}")
            print(f"                        | everything unknown:     T {al_T:8.3f}   (F, T) {al_F:8.3f}"
                  f"   -> bound on s.e.(c) at 72 per arm: T {np.sqrt(1 / (72 * al_T)):.3f}   (F, T) {se72:.3f}")
            print(f"      psi: s.e. at 72 per arm | plug-in ratio of means {np.sqrt(vnp / 72):.4f} | bound, T only {np.sqrt(bound / 72):.4f}"
                  f" (RE {bound / vnp:.3f}) | bound, T only, depth unknown {np.sqrt(bound_l / 72):.4f} | bound with F {np.sqrt(bound_F / 72):.4f} (RE {bound_F / vnp:.3f})")
            print(f"      certifying c >= .90 against the truth (asymptotic bound, (F, T), everything unknown): {ncert:.0f} per arm"
                  f"   [condition numbers: T {np.linalg.cond(ST):.1e}, (F, T) {np.linalg.cond(SF):.1e}]", flush=True)
            if c == 1.0:
                # curves for the record and the figure: pmfs, score for c, the two influence functions
                pH, sH = m.scores('HIGH', th, names_T, False)
                pL, sL = m.scores('LOW', th, names_T, False)
                Ii = np.linalg.inv(0.5 * ST[:nT, :nT])
                curves[f"{k}|{r}"] = dict(
                    t=lc.TGRID.tolist(), pH=pH.tolist(), pL=pL.tolist(),
                    p0=m.pT('HIGH', {**th, 'c': 0.0}).tolist(),
                    score_c_H=sH[0].tolist(), score_c_L=sL[0].tolist(),
                    phi_eff_H=(gpsi @ Ii @ sH).tolist(), phi_eff_L=(gpsi @ Ii @ sL).tolist(),
                    phi_np_H=(2 * (lc.TGRID - muH) / muL).tolist(), phi_np_L=(-2 * psi * (lc.TGRID - muL) / muL).tolist(),
                    psi=psi, grad=dict(zip(names_T, gpsi.tolist())), re=bound / vnp)
json.dump(curves, open('records/likelihood_curves_I039.json', 'w'))

# gate GR (stated in the freeze; see the note printed)
cv = curves['P1|event']
pH, pL = np.array(cv['pH']), np.array(cv['pL'])
m = M[('P1', 'event')]
_, sH = m.scores('HIGH', lc.BASE, ['c', 'kap', 'sig', 'q'], False)
_, sL = m.scores('LOW', lc.BASE, ['c', 'kap', 'sig', 'q'], False)
lhs = 0.5 * ((np.array(cv['phi_np_H']) * pH) @ sH.T + (np.array(cv['phi_np_L']) * pL) @ sL.T)
print("\n   gate GR at P1, event rule: E[phi_np s_j] against d psi / d theta_j: " +
      "  ".join(f"{a:+.5f} / {b:+.5f}" for a, b in zip(lhs, cv['grad'].values())))
print("   (the two sides are the same finite difference of the arm means, so this is an identity, not an independent check)")
cov = 0.5 * ((np.array(cv['phi_np_H']) * pH) @ np.array(cv['phi_eff_H']) + (np.array(cv['phi_np_L']) * pL) @ np.array(cv['phi_eff_L']))
var_eff = 0.5 * ((np.array(cv['phi_eff_H']) ** 2) @ pH + (np.array(cv['phi_eff_L']) ** 2) @ pL)
var_np = 0.5 * ((np.array(cv['phi_np_H']) ** 2) @ pH + (np.array(cv['phi_np_L']) ** 2) @ pL)
print(f"   projection check: Cov(phi_np, phi_eff) {cov:.4f} = Var(phi_eff) {var_eff:.4f}; Var(phi_np) {var_np:.4f}; "
      f"correlation {cov / np.sqrt(var_eff * var_np):.3f}")

# ------------------------------------------------------------------ 4. the functions themselves
print("\n4. P1, event rule, full coupling: the model-generated distribution of T and the functions built on it")
print("      t     p(t|HIGH)  p(t|LOW)  p(t|HIGH, c=0)   score for c (HIGH)   plug-in IF (HIGH)   efficient IF (HIGH)")
for t in (-60, -40, -20, -10, 0, 10, 20, 30, 40, 60, 80, 100):
    i = int(round((t + 200) / 2.5))
    print(f"    {t:5.0f}   {cv['pH'][i]:.5f}   {cv['pL'][i]:.5f}   {cv['p0'][i]:.5f}          {cv['score_c_H'][i]:+8.3f}           "
          f"{cv['phi_np_H'][i]:+7.3f}             {cv['phi_eff_H'][i]:+7.3f}")

# ------------------------------------------------------------------ 5. state dependence in the population
print("\n5. the model's joint distribution of (F, T): within-arm Pearson correlation and mutual information (nats per participant)")
print("   point  rule      corr HIGH   corr LOW    MI HIGH    MI LOW")
for k in G:
    for r in ec.RULES:
        row = []
        for arm in ('HIGH', 'LOW'):
            J = M[(k, r)].pFT(arm, lc.BASE)
            pf, pt = J.sum(1), J.sum(0)
            mf, mt = lc.REP @ pf, lc.TGRID @ pt
            cov_ft = (lc.REP - mf) @ J @ (lc.TGRID - mt)
            cor = cov_ft / np.sqrt(((lc.REP - mf) ** 2 @ pf) * ((lc.TGRID - mt) ** 2 @ pt))
            ind = np.outer(pf, pt)
            mi = np.sum(np.where(J > 1e-300, J * np.log(np.maximum(J, 1e-300) / np.maximum(ind, 1e-300)), 0.0))
            row += [cor, mi]
        print(f"   {k}     {r:7s}   {row[0]:+.3f}      {row[2]:+.3f}      {row[1]:.4f}     {row[3]:.4f}")

# ------------------------------------------------------------------ 6. aggregate paths
print("\n6. aggregate residual error after t evidence events (event rule, weight .5 x gain, gate states held at probe time,")
print("   attentive agents): the population against a representative agent with the mean gain")
print("   point   share at 0 |   t = 1          2          5         10         20         50      limit")
for k in G:
    g = G[k]['HIGH']
    w = pg.OMEGA * lc.LGRID
    agg = [g @ (1 - w) ** t for t in (1, 2, 5, 10, 20, 50)]
    rep = [(1 - g @ w) ** t for t in (1, 2, 5, 10, 20, 50)]
    z = raw0[k]['HIGH'][1]
    print(f"   {k}      {z:.3f}     | " + "  ".join(f"{a:.3f}/{b:.3f}" for a, b in zip(agg, rep)) + f"   {z:.3f}/0.000")
print("   (each cell: population / representative agent)")
